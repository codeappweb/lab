#!/usr/bin/env node
// gen-dashboard.mjs — local experiment dashboard (reports/dashboard.md).
// Reads progress.json, manifest, audit + scoring reports. No Google data:
// discovery observations live in reports/google-discovery.json and are
// recorded manually.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { readdirSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname;
const read = p => { try { return JSON.parse(readFileSync(join(ROOT, p), 'utf8')); } catch { return null; } };

const progress = read('data/progress.json');
const manifest = readFileSync(join(ROOT, 'data/article-manifest.jsonl'), 'utf8').split('\n').filter(Boolean).map(l => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
const audit = read('reports/self-heal-audit.json');
const seo = read('reports/seo-scores.json');
const legal = read('reports/legal-freshness.json');
const discovery = read('reports/google-discovery.json');

const posts = readdirSync(join(ROOT, '_posts')).filter(f => f.endsWith('.md')).length;
const publishedManifest = manifest.filter(r => r.status === 'published').length;
const planned = manifest.filter(r => !['published', 'merge', 'skip'].includes(r.status)).length;
const observed = discovery ? discovery.filter(d => d.status === 'OBSERVED').length : 0;
const notObserved = discovery ? discovery.filter(d => d.status === 'NOT_OBSERVED').length : 0;

const rows = [
  ['Target Articles', '20,000'],
  ['Generated / Published (posts on disk)', String(posts)],
  ['Manifest: published', String(publishedManifest)],
  ['Manifest: open topics', String(planned)],
  ['Needs Legal Review', legal ? String(legal.needs_legal_review.length) : 'n/a'],
  ['Orphan/Broken (MEDIUM+)', audit ? String(audit.counts.MEDIUM + audit.counts.HIGH + audit.counts.CRITICAL) : 'n/a'],
  ['Average internal SEO score', seo ? seo.average + '/100' : 'n/a'],
  ['Google discovery: OBSERVED (manual)', String(observed)],
  ['Google discovery: NOT_OBSERVED (manual)', String(notObserved)],
  ['Search Console', 'NOT CONNECTED (by design)'],
  ['Google verification meta', 'NONE (by design)'],
  ['Manual submission', 'NONE (by design)']
];

let md = '# 20K Experiment Dashboard\n\n';
md += '> Automated local report. Google discovery data is recorded manually only.\n\n';
md += '| Metric | Value |\n|---|---|\n';
for (const [k, v] of rows) md += '| ' + k + ' | ' + v + ' |\n';
if (audit) md += '\n## Audit counts\n\n' + JSON.stringify(audit.counts) + '\n';
md += '\n*Regenerated by scripts/gen-dashboard.mjs (CI).*\n';
md += '\n*Last successful deployment, last audit and freshness scan: see CI runs and reports/.*\n';

const fs = await import('node:fs');
fs.mkdirSync(join(ROOT, 'reports'), { recursive: true });
fs.writeFileSync(join(ROOT, 'reports/dashboard.md'), md);
console.log('dashboard: reports/dashboard.md written');
